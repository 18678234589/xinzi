<h5>共同接单与按单补助</h5>
<p>同一订单选择多名客服时，报单人不独占分成。默认同组均分：两人各 50%，三人各约 1/3；同组权重合计必须为 100%。订单按订单号 / 支付流水关联，各参与人看到的是同一订单，不因二次上传多发一份。</p>
<p>组池算法：先计算整单分成池，再分配。<strong>整单分成池 =（已核验净实收 − 直接成本 − 整单服务费）× 该业务分成比例 + 整单按单补助</strong>。本人金额按权重分摊；服务费只扣一次，按单补助只发一池。例如客服池合计 ¥40，两位客服各 ¥20。金额按分分配，尾差计入最高权重者，权重相同则归参与人列表中的首位。</p>
<p>小程序模板（新订单）客服组：5% + 整单 ¥20；小程序定制客服组：10% + 整单 ¥10（原规则售价低于 ¥50 不计）。两位客服共同接模板单，补助各 ¥10；共同接定制单，补助各 ¥5。技术仍按规则中心对应技术岗位比例及补助核算，不套客服规则。</p>
<p class="small text-muted mb-0">上述组池分摊适用于各业务的 pool 规则；网站模板主次客服保留原核算表约定的服务费分摊口径（两人各 1.5%），不强行改写已有业务约定。individual 独立岗位按各岗位约定算法执行，不强制均分其独立报酬。多人岗位对应不同规则时按各自有效规则及约定权重计算，财务须确认岗位与权重。已锁定月份不重写，历史错误经审计更正；全额退款、售价门槛、补助名单等原有限制继续生效。</p>
