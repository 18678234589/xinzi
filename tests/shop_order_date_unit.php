<?php
// 店铺订单“时间”单元格各种写法的识别（纯函数测试，不连数据库）：php tests/shop_order_date_unit.php
require_once __DIR__ . '/../includes/ShopOrderDate.php';
require_once __DIR__ . '/../includes/ProjectImportParse.php';
$fail = 0;
$cases = [
    ['2026081012:21:30', '2026-08-10', '2026-08-10 12:21:30'],
    ['2026081109:11:58', '2026-08-11', '2026-08-11 09:11:58'],
    ['20260703093827', '2026-07-03', '2026-07-03 09:38:27'],
    ['20260810', '2026-08-10', '2026-08-10 00:00:00'],
    ['2026-8-7 10:00', '2026-08-07', '2026-08-07 10:00:00'],
    ['2026-8-5 17:52', '2026-08-05', '2026-08-05 17:52:00'],
    ['2026-08-03 14:42:40 ', '2026-08-03', '2026-08-03 14:42:40'],
    ['2026/7/1 934', '2026-07-01', '2026-07-01 09:34:00'],
    ['2026/7/1 1534', '2026-07-01', '2026-07-01 15:34:00'],
    ['2026年8月7日 9:05', '2026-08-07', '2026-08-07 09:05:00'],
    ['2026.8.7', '2026-08-07', '2026-08-07 00:00:00'],
    ['46237.612962963', '2026-08-03', '2026-08-03 14:42:40'],
];
foreach ($cases as [$in, $date, $time]) {
    $r = sod_parse($in);
    $ok = $r && $r['date'] === $date && $r['time'] === $time;
    if (!$ok) $fail++;
    echo ($ok ? '[OK] ' : '[FAIL] ') . $in . ' => ' . json_encode($r) . "\n";
}
foreach (['', '客户付款', '2026-13-40', '12:00', '1999/1/1'] as $bad) {
    $ok = sod_parse($bad) === null; if (!$ok) $fail++;
    echo ($ok ? '[OK] ' : '[FAIL] ') . '无法识别：“' . $bad . '”' . "\n";
}
$ok = ps_import_date('2026081012:21:30') === '2026-08-10' && ps_import_date('9.05') !== null && ps_import_date('2026.8.3') === '2026-08-03';
if (!$ok) $fail++;
echo ($ok ? '[OK] ' : '[FAIL] ') . "项目导入的日期识别同样认连写日期时间，原有写法不受影响\n";
echo $fail ? "失败 $fail 项\n" : "全部通过\n";
exit($fail ? 1 : 0);
